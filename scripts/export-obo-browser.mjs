import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const source=new URL('../components/obo/runtime/',import.meta.url);
const files=['index.mjs','contracts.mjs','validation.mjs','cpu.mjs','memory.mjs','flows.mjs','synchronization.mjs','simulation.worker.mjs'];
const contents=await Promise.all(files.map(file=>readFile(new URL(file,source))));
const hash=createHash('sha256');contents.forEach(bytes=>hash.update(bytes));
const release=hash.digest('hex').slice(0,20);
const target=new URL(`../public/obo-runtime/${release}/`,import.meta.url);
await mkdir(target,{recursive:true});
await Promise.all(files.map((file,index)=>writeFile(new URL(file,target),contents[index])));
await writeFile(new URL('worker-release.ts',source),`// Generated by scripts/export-obo-browser.mjs.\nexport const workerUrl='/obo-runtime/${release}/simulation.worker.mjs';\n`);
console.log(`OBO browser worker exported: ${release}`);
